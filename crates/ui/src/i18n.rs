pub fn t(key: &str) -> &'static str {
    let Some((_, de, en)) = STRINGS.iter().find(|(k, _, _)| *k == key) else {
        tracing_missing(key);
        // Leak-free fallback: unknown keys map to a static marker.
        return "??";
    };
    let other = |table: &[(&'static str, &'static str)]| table.iter().find(|(k, _)| *k == key).map_or(*en, |(_, s)| *s);
    match LANG.load(Ordering::Relaxed) {
        0 => de,
        2 => other(ES),
        3 => other(IT),
        _ => en,
    }
}

fn tracing_missing(_key: &str) {
    #[cfg(debug_assertions)]
    eprintln!("missing translation key: {_key}");
}

/// Translate with `{name}` placeholders.
pub fn tf(key: &str, args: &[(&str, &str)]) -> String {
    let mut s = t(key).to_string();
    for (k, v) in args {
        s = s.replace(&format!("{{{k}}}"), v);
    }
    s
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn keys_unique() {
        let mut seen = std::collections::HashSet::new();
        for (k, _, _) in STRINGS {
            assert!(seen.insert(*k), "duplicate key {k}");
        }
    }

    /// Spanish and Italian cover exactly the keys of [`STRINGS`] and keep every `{placeholder}`.
    #[test]
    fn translations_complete() {
        let placeholders = |s: &str| {
            let mut v: Vec<String> = s.split('{').skip(1).filter_map(|p| p.split_once('}').map(|(name, _)| name.to_string())).collect();
            v.sort();
            v
        };
        for (name, table) in [("es", ES), ("it", IT)] {
            let mut seen = std::collections::HashSet::new();
            for (k, text) in table {
                assert!(seen.insert(*k), "{name}: duplicate key {k}");
                let (_, _, en) = STRINGS.iter().find(|(key, _, _)| key == k).unwrap_or_else(|| panic!("{name}: unknown key {k}"));
                assert_eq!(placeholders(text), placeholders(en), "{name}: placeholders of {k}");
            }
            for (k, _, _) in STRINGS {
                assert!(seen.contains(k), "{name}: missing key {k}");
            }
        }
    }

    #[test]
    fn core_error_keys_exist() {
        use scan_core::ports::PortError;
        use scan_core::{RangeErrorKind as R, ScanWarning};
        let range = [
            R::InvalidPrefix,
            R::PrefixV4,
            R::PrefixV6,
            R::Ipv6TooLarge,
            R::InvalidAddress,
            R::InvalidStart,
            R::InvalidEnd,
            R::EndBeforeStart,
            R::Invalid,
            R::Empty,
            R::TooLarge,
        ];
        let keys = range
            .iter()
            .map(|k| k.key())
            .chain([PortError::Invalid(String::new()).key(), PortError::InvalidRange(String::new()).key(), PortError::Zero.key()])
            .chain([ScanWarning::IcmpFallback.key(), ScanWarning::MdnsUnavailable(String::new()).key()]);
        for k in keys {
            assert!(STRINGS.iter().any(|(key, _, _)| *key == k), "missing translation {k}");
        }
    }

    #[test]
    fn placeholders() {
        set_language(Language::German);
        assert_eq!(tf("sb.summary", &[("a", "5"), ("d", "0"), ("u", "0")]), "5 lebendig, 0 keine Reaktion, 0 unbekannt");
        set_language(Language::Italian);
        assert_eq!(tf("sb.summary", &[("a", "5"), ("d", "0"), ("u", "0")]), "5 attivi, 0 nessuna risposta, 0 sconosciuti");
        set_language(Language::German);
    }
}
