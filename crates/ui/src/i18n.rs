use std::sync::atomic::{AtomicU8, Ordering};
use storage::Language;

static LANG: AtomicU8 = AtomicU8::new(0); // 0 = de, 1 = en, 2 = es, 3 = it

pub fn set_language(lang: Language) {
    let code = match lang {
        Language::German => 0,
        Language::English => 1,
        Language::Spanish => 2,
        Language::Italian => 3,
        Language::System => {
            let locale = sys_locale::get_locale().unwrap_or_default().to_lowercase();
            match locale.get(..2) {
                Some("de") => 0,
                Some("es") => 2,
                Some("it") => 3,
                _ => 1,
            }
        }
    };
    LANG.store(code, Ordering::Relaxed);
}

